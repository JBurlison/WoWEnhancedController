"""Locale export/audit helpers; never translate saved user content."""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
ADDON = ROOT / 'WoWEnhancedController'
# Skip comments and long-bracket strings (including restricted snippets).
TOKENS = re.compile(r'--\[(=*)\[.*?\]\1\]|--[^\n]*|\[(=*)\[.*?\]\2\]|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', re.S)

def literals(text):
    for token in TOKENS.finditer(text):
        raw = token.group()
        if raw[:1] in ('"', "'"):
            # Production strings use JSON-compatible escapes, plus Lua \'.
            value = bytes(raw[1:-1], 'utf8').decode('utf8')
            value = value.replace('\\"', '"').replace("\\'", "'").replace('\\n', '\n').replace('\\t', '\t').replace('\\\\', '\\')
            yield token, value

def inventory():
    values = {}
    for path in ADDON.glob('*.lua'):
        if path.name.startswith('Locale'): continue
        text = path.read_text(encoding='utf8')
        for token, value in literals(text):
            if re.search('[A-Za-z]', value) and (' ' in value or re.match('^[A-Z][a-z]+[!?:.]?$' ,value)):
                if not value.startswith(('Interface', 'Fonts', '^', 'self:', 'return ', 'WoWEnhanced', 'BINDING_')):
                    values.setdefault(value, set()).add(path.name)
    return values

EXCLUDE = {'Button', 'Frame', 'Camera', 'Movement', 'Highlight', 'Confirm', 'Toggle', 'Professions', 'Search', 'Wheel', 'Generic', 'Xbox', 'Nintendo', 'Enhanced Controller'}
EXTRA = {'All contexts', 'All chat', 'This context', 'Default', 'Send / Done', 'Phrase layer', 'Focus', 'Auto', '%.1fs',
         'Controller keyboard, contextual phrases, and party/raid spell wheels for WoW Forever.'}
LOCALES = ['deDE','frFR','esES','itIT','ptBR','ruRU','koKR','zhCN','zhTW']
CATALOG = ROOT / 'localization/catalog.json'

def seed():
    keys = set(inventory()) | EXTRA
    keys = {k for k in keys if k not in EXCLUDE and k == k.strip()
            and not k.startswith(('if ', 'return ', '[petbattle]', '|c', '/cast'))}
    if CATALOG.exists():
        data = json.loads(CATALOG.read_text(encoding='utf8'))
        old = data['messages']
    else: old = {}
    CATALOG.parent.mkdir(exist_ok=True)
    CATALOG.write_text(json.dumps({'locales':LOCALES,'messages':{k:old.get(k,[]) for k in sorted(keys)}}, ensure_ascii=False, indent=2)+'\n', encoding='utf8')
    print(f'{len(keys)} catalog keys')

def wrap():
    keys = set(json.loads(CATALOG.read_text(encoding='utf8'))['messages']) - {'Auto'}
    for path in ADDON.glob('*.lua'):
        if path.name.startswith('Locale'): continue
        text = path.read_text(encoding='utf8')
        edits=[]
        for token,value in literals(text):
            if value not in keys: continue
            prefix=text[max(0,token.start()-60):token.start()]
            line=text[text.rfind('\n',0,token.start())+1:text.find('\n',token.end())]
            if re.search(r'W\.L\[\s*$|W\.L\.Format\(\s*$',prefix) or 'SetAttribute("command"' in line: continue
            # Settings helpers perform the lookup from their source-key args.
            if path.name=='Settings.lua': continue
            edits.append((token.start(),token.end(),'W.L['+token.group()+']'))
        for start,end,replacement in reversed(edits): text=text[:start]+replacement+text[end:]
        path.write_text(text,encoding='utf8')

def export():
    data=json.loads(CATALOG.read_text(encoding='utf8'))
    folder=ADDON/'Locales';folder.mkdir(exist_ok=True)
    for i,locale in enumerate(LOCALES):
        rows=['-- Generated by tools/localization.py; edit localization/catalog.json.', 'local _, W = ...',f'if W.Locale.code ~= "{locale}" then return end','local L = W.L']
        for key,values in data['messages'].items():
            if len(values)==9:
                rows.append('L['+json.dumps(key,ensure_ascii=False)+'] = '+json.dumps(values[i],ensure_ascii=False))
        (folder/(locale+'.lua')).write_text('\n'.join(rows)+'\n',encoding='utf8')
    incomplete=[k for k,v in data['messages'].items() if len(v)!=9]
    print(f'{len(data["messages"])-len(incomplete)}/{len(data["messages"])} translated keys; {len(incomplete)} pending')
    note='Controller keyboard, contextual phrases, and party/raid spell wheels for WoW Forever.'
    if len(data['messages'].get(note,[]))==9:
        toc=ADDON/'WoWEnhancedController.toc'
        lines=[line for line in toc.read_text(encoding='utf8').splitlines() if not re.match(r'## Notes-[a-zA-Z]+:',line)]
        index=next(i for i,line in enumerate(lines) if line.startswith('## Notes:'))+1
        notes=[f'## Notes-{locale}: {data["messages"][note][i]}' for i,locale in enumerate(LOCALES)]
        notes.append('## Notes-esMX: '+data['messages'][note][LOCALES.index('esES')])
        lines[index:index]=notes
        toc.write_text('\n'.join(lines)+'\n',encoding='utf8')

if __name__ == '__main__' and len(sys.argv)>1:
    {'seed':seed,'wrap':wrap,'export':export}[sys.argv[1]]()
elif __name__ == '__main__':
    values = inventory()
    target = ROOT / '.tools/i18n-inventory.json'
    target.write_text(json.dumps({k: sorted(v) for k,v in sorted(values.items())}, ensure_ascii=False, indent=2), encoding='utf8')
    for i, value in enumerate(sorted(values), 1): print(f'{i}: {value!r}')
